/**
 * A haystack for the Bitcoin wallet's address lookups.
 *
 * A light wallet has to ask somebody whether its addresses have money on
 * them, and asking is the leak: whoever answers, and whoever carries the
 * question, learns that those addresses belong together. On this site that
 * is our own Worker, and behind it Cloudflare, which is exactly the kind of
 * quiet observation the rest of the page exists to refuse.
 *
 * Padded mode mixes every real lookup into a shuffled batch of these. They
 * are real mainnet P2WPKH addresses harvested from settled blocks, so they
 * are the same shape as the ones the wallet derives (bc1q, 42 characters)
 * and, crucially, most of them have history: a haystack of never-used
 * addresses would leave the wallet's used ones standing out on their own.
 *
 * What this does and does not buy is written down in docs/wallet-privacy.md
 * and said plainly on the page. In short: it hides the wallet from someone
 * reading the request log, and it does not hide it from someone willing to
 * cluster the addresses on the chain itself. The strong answer remains your
 * own Esplora server, which is one field away on the same panel.
 *
 * Harvested 2026-08-07 from mempool.space. They belong to strangers; nothing here spends, watches or
 * reports on them, and the wallet ignores every answer that comes back for
 * one.
 */

